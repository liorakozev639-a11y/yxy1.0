def _build_additional_activity_rows() -> list[tuple[str, str, str, int, int, str, str, tuple[str, ...]]]:
    rows: list[tuple[str, str, str, int, int, str, str, tuple[str, ...]]] = []
    existing_counts = Counter(category for _, _, category, *_ in _ACTIVITY_ROWS)
    for category in CATEGORIES:
        prefix = _TASK_PREFIX_BY_CATEGORY[category]
        start = existing_counts[category] + 1
        blueprints = (
            _ADDITIONAL_ACTIVITY_BLUEPRINTS[category]
            + _FURTHER_ACTIVITY_BLUEPRINTS[category]
        )
        for offset, (title, duration, budget, outing, company, scenarios) in enumerate(
            blueprints,
            start=start,
        ):
            rows.append(
                (
                    f"task_{prefix}_{offset:02d}",
                    title,
                    category,
                    duration,
                    budget,
                    outing,
                    company,
                    scenarios,
                )
            )
    return rows


